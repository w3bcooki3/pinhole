#!/usr/bin/env node
// Runs the fixture suite and writes the real pass count into README.md
// between the fixture-count markers.
//
//   node scripts/fixture-count.mjs          update README.md
//   node scripts/fixture-count.mjs --check  exit 1 if README.md is stale or
//                                            any fixture assertion fails (CI)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const readmePath = join(root, 'README.md');

const outFile = join(mkdtempSync(join(tmpdir(), 'pinhole-count-')), 'result.json');
try {
  execFileSync('npx', ['vitest', 'run', 'packages/engine/test/fixtures.test.ts', '--reporter=json', `--outputFile=${outFile}`], { cwd: root, stdio: 'ignore' });
} catch {
  // vitest exits non-zero when a test fails; the report is still written.
}
const result = JSON.parse(readFileSync(outFile, 'utf8'));
const passed = result.numPassedTests;
const total = result.numTotalTests;
const scenarios = readdirSync(join(root, 'fixtures'), { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(root, 'fixtures', d.name, 'expected.json'))).length;

const line = `**Fixtures: ${passed} of ${total} assertions pass across ${scenarios} scenarios.** Generated by \`npm run fixture-count\`; CI fails if this line is out of date.`;
const readme = readFileSync(readmePath, 'utf8');
const re = /<!-- fixture-count:start -->[\s\S]*?<!-- fixture-count:end -->/;
if (!re.test(readme)) {
  console.error('README.md has no fixture-count markers.');
  process.exit(1);
}
const updated = readme.replace(re, `<!-- fixture-count:start -->\n${line}\n<!-- fixture-count:end -->`);

if (process.argv.includes('--check')) {
  if (passed !== total) {
    console.error(`${total - passed} fixture assertion(s) fail.`);
    process.exit(1);
  }
  if (updated !== readme) {
    console.error('README.md fixture count is out of date; run `npm run fixture-count`.');
    process.exit(1);
  }
  console.log(line);
} else {
  writeFileSync(readmePath, updated);
  console.log(line);
}
